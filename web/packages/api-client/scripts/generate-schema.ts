// Generates src/schema.d.ts from backend/openapi.yaml with openapi-typescript (ADR-09, C-8).
//   npm run api:generate   writes the file
//   npm run api:check      fails (exit 1) when the committed file is out of date, like the backend's own openapi.yaml test
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const packageDir = resolve(import.meta.dirname, "..");
export const specPath = resolve(packageDir, "../../../backend/openapi.yaml");
export const schemaPath = resolve(packageDir, "src/schema.d.ts");

const header = [
  "/**",
  " * GENERATED by `npm run api:generate` from backend/openapi.yaml with openapi-typescript. Do not edit by hand:",
  " * change the backend, regenerate the YAML there, then regenerate this file (ADR-09, C-8).",
  " */",
  "",
].join("\n");

// The text the file should contain right now.
export async function generateSchemaText(): Promise<string> {
  const ast = await openapiTS(pathToFileURL(specPath));
  return header + astToString(ast);
}

// Line endings must not matter (Windows and Linux), and the file ends with one newline.
const normalise = (text: string): string => text.replace(/\r\n/g, "\n").trimEnd() + "\n";

export function isUpToDate(generated: string, committed: string): boolean {
  return normalise(generated) === normalise(committed);
}

// Only when run as a script (not when a test imports this file).
if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  const generated = await generateSchemaText();
  if (process.argv.includes("--check")) {
    if (!isUpToDate(generated, readFileSync(schemaPath, "utf8"))) {
      console.error("src/schema.d.ts is out of date with backend/openapi.yaml. Run `npm run api:generate` and commit the result.");
      process.exit(1);
    }
    console.log("src/schema.d.ts matches backend/openapi.yaml.");
  } else {
    writeFileSync(schemaPath, normalise(generated));
    console.log(`Wrote ${schemaPath}`);
  }
}
